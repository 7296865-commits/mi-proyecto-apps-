def obtener_usuarios():
    conn = conectar()
    datos = pd.read_sql_query(
        "SELECT * FROM Usuario ORDER BY nombre",
        conn
    )
    conn.close()
    return datos


def obtener_diario():
    conn = conectar()

    datos = pd.read_sql_query("""
        SELECT
            CheckIn.id_checkin,
            Usuario.nombre AS usuario,
            CheckIn.fecha,
            CheckIn.nivel_animo,
            CheckIn.nota
        FROM CheckIn
        INNER JOIN Usuario
        ON CheckIn.id_usuario = Usuario.id_usuario
        ORDER BY CheckIn.fecha DESC
    """, conn)

    conn.close()
    return datos

