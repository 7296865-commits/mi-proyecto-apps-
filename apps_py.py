        if nombre.strip():

            conn = conectar()
            cursor = conn.cursor()

            cursor.execute(
                "SELECT id_usuario FROM Usuario WHERE LOWER(nombre)=LOWER(?)",
                (nombre.strip(),)
            )

            existe = cursor.fetchone()

            if existe:
                st.warning("Este usuario ya está registrado.")
            else:
                cursor.execute(
                    "INSERT INTO Usuario (nombre) VALUES (?)",
                    (nombre.strip(),)
                )

                conn.commit()
                st.success("Usuario registrado correctamente.")

            conn.close()

