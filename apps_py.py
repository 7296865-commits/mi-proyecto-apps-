def conectar():
    return sqlite3.connect(DB)

# ==========================================
# CREAR TABLAS
# ==========================================

def crear_tablas():
    conn = conectar()
    cursor = conn.cursor()

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS Usuario (
        id_usuario INTEGER PRIMARY KEY AUTOINCREMENT,
        nombre TEXT NOT NULL
    )
    """)

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS CheckIn (
        id_checkin TEXT PRIMARY KEY,
        id_usuario INTEGER,
        fecha TEXT,
        nivel_animo INTEGER,
        nota TEXT,
        FOREIGN KEY (id_usuario) REFERENCES Usuario(id_usuario)
    )
    """)

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS Contexto (
        id_contexto INTEGER PRIMARY KEY AUTOINCREMENT,
        id_usuario INTEGER,
        horas_sueno INTEGER,
        carga_academica INTEGER,
        tiempo_redes INTEGER
    )
    """)

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS Tecnica (
        id_tecnica INTEGER PRIMARY KEY AUTOINCREMENT,
        id_usuario INTEGER,
        tecnica TEXT
    )
    """)

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS Retroalimentacion (
        id_retroalimentacion INTEGER PRIMARY KEY AUTOINCREMENT,
        id_usuario INTEGER,
        opinion TEXT,
        mejora TEXT
    )
    """)

    conn.commit()
    conn.close()

crear_tablas()

